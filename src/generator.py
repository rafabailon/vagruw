"""Rendering of the self-contained Vagrantfile and its base bootstrap script.

The generated Vagrantfile intentionally places every Ruby statement at column
zero. Ruby does not require block indentation, and this keeps the generated
artifact consistent with the prose-oriented documentation style requested for
this project.
"""

from __future__ import annotations

from model import Deployment


def render_bootstrap(deployment: Deployment) -> str:
    """Return the shell provisioner that prepares every lab machine."""
    host_lines = "\n".join(deployment.hosts_entries())
    return f"""#!/usr/bin/env bash
set -euo pipefail
if command -v cloud-init >/dev/null 2>&1; then
cloud-init status --wait >/dev/null 2>&1 || true
fi
if grep -q "vagruw managed hosts" /etc/hosts; then
sed -i '/# vagruw managed hosts/,/# vagruw end hosts/d' /etc/hosts
fi
cat >> /etc/hosts <<'VAGRUW_HOSTS'
# vagruw managed hosts
{host_lines}
# vagruw end hosts
VAGRUW_HOSTS
printf '%s\\n' "vm.max_map_count=262144" > /etc/sysctl.d/99-vagruw.conf
sysctl -p /etc/sysctl.d/99-vagruw.conf >/dev/null
if command -v timedatectl >/dev/null 2>&1; then
timedatectl set-timezone UTC >/dev/null 2>&1 || true
fi
echo "[vagruw] Base bootstrap complete on $(hostname)"
"""


def _quote(value: str) -> str:
    """Return a Ruby-safe double-quoted string."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_vagrantfile(deployment: Deployment) -> str:
    """Render a complete Vagrantfile for the selected deployment."""
    lines = [
        "# -*- mode: ruby -*-",
        "# vi: set ft=ruby :",
        "#",
        "# Generated by Vagruw. Regenerate with 'vagruw generate --force' instead of",
        "# editing this file by hand when the topology or the Wazuh release changes.",
        f"# Project: {deployment.project}",
        f"# Topology: {deployment.topology}",
        f"# Wazuh version: {deployment.wazuh_version}",
        f"# Base box: {deployment.box}",
        f"# Provider: {deployment.provider}",
        f"# Network: {deployment.network}",
        "#",
        "# Generic images are published through the HashiCorp Vagrant registry.",
        "# The private network is host-only and is not reachable from the internet.",
        "",
        "$vagruw_bootstrap = <<'VAGRUW_BOOTSTRAP'",
        render_bootstrap(deployment).rstrip("\n"),
        "VAGRUW_BOOTSTRAP",
        "",
        'Vagrant.configure("2") do |config|',
        f"config.vm.box = {_quote(deployment.box)}",
        "config.vm.box_check_update = false",
        "config.vm.boot_timeout = 900",
        "config.ssh.keep_alive = true",
        'config.vm.synced_folder ".", "/vagrant", disabled: true',
        f"config.vm.post_up_message = {_quote('Vagruw lab ready. Install Wazuh with: vagruw install')}",
        "",
    ]
    for node in deployment.nodes:
        resource = deployment.resource_for(node.role)
        lines.extend(
            [
                f"config.vm.define {_quote(node.name)} do |node|",
                f"node.vm.hostname = {_quote(node.name)}",
                f'node.vm.network "private_network", ip: {_quote(node.ip)}',
                'node.vm.provider "virtualbox" do |provider|',
                f"provider.name = {_quote(node.name)}",
                f"provider.memory = {resource['memory_mb']}",
                f"provider.cpus = {resource['cpus']}",
                'provider.customize ["modifyvm", :id, "--natdnshostresolver1", "on"]',
                'provider.customize ["modifyvm", :id, "--audio", "none"]',
                "end",
                'node.vm.provider "libvirt" do |provider|',
                f"provider.memory = {resource['memory_mb']}",
                f"provider.cpus = {resource['cpus']}",
                "end",
                'node.vm.provision "shell", inline: $vagruw_bootstrap, privileged: true',
                "end",
                "",
            ]
        )
    lines.append("end")
    return "\n".join(lines) + "\n"
